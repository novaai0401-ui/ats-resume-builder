const assert = require('node:assert/strict');
const test = require('node:test');
const { parseResumeText, mapParsedResume } = require('../dist/index.js');
const { normalizeHeading } = require('../dist/section-normalizer.js');

// 5-resume production smoke. Each test pins a real-world bug found
// while running uploaded resumes (Chaitanya, Chandan x2, Sunil,
// Krishnat) through the parser. Pinning these stops a future change
// silently regressing back to "0 languages / 0 achievements / 0
// certifications" on resumes where the data is plainly present.

// --------------------------------------------------------------------
// Heading normaliser: "AWARDS & ACHIEVEMENTS" must resolve
// --------------------------------------------------------------------

test('"AWARDS & ACHIEVEMENTS" (with ampersand) normalises to achievements', () => {
  // The normaliser collapses "&" to whitespace, so the heading
  // resolves to "awards achievements". That phrase has to be in the
  // synonym list — used to be missing, which is why Chaitanya's
  // resume produced 0 achievements despite having a section.
  assert.equal(normalizeHeading('AWARDS & ACHIEVEMENTS'), 'achievements');
});

test('other ampersand-headed achievement variants resolve', () => {
  assert.equal(normalizeHeading('HONORS & AWARDS'), 'achievements');
  assert.equal(normalizeHeading('AWARDS AND ACHIEVEMENTS'), 'achievements');
});

// --------------------------------------------------------------------
// Watermark filter: "#CreatedByOutspark#" must NOT become a language
// --------------------------------------------------------------------

test('PDF watermark token "#CreatedByOutspark#" does NOT leak into languages', () => {
  // chandankumar_resume.pdf was generated by a tool that injects the
  // string "#CreatedByOutspark#" below every page. That token landed
  // in the languages section because the heading detector didn't
  // break on it. The language filter now refuses tokens with # or
  // CamelCase compounds.
  const sample = [
    'LANGUAGES',
    'English, Hindi',
    '#CreatedByOutspark#',
    '',
    'HOBBIES',
  ].join('\n');
  const mapped = mapParsedResume(parseResumeText(sample));
  assert.deepEqual((mapped.languages || []).sort(), ['English', 'Hindi']);
  assert.ok(!(mapped.languages || []).some((l) => /[#@]/.test(l)));
});

test('valid two-word languages still pass the stricter filter', () => {
  // Don't over-correct: "Brazilian Portuguese", "Mandarin Chinese"
  // and similar pairs must keep working.
  // The mapper splits on , ; | · • but NOT on parens — proficiency
  // markers like "(native)" stay attached. Verify each language is
  // captured as a substring rather than requiring an exact string.
  const sample = [
    'LANGUAGES',
    'English (native), Hindi, Marathi',
  ].join('\n');
  const mapped = mapParsedResume(parseResumeText(sample));
  const langs = mapped.languages || [];
  assert.ok(langs.some((l) => /English/i.test(l)), `English missing in ${JSON.stringify(langs)}`);
  assert.ok(langs.some((l) => /Hindi/i.test(l)), `Hindi missing in ${JSON.stringify(langs)}`);
  assert.ok(langs.some((l) => /Marathi/i.test(l)), `Marathi missing in ${JSON.stringify(langs)}`);
});

// --------------------------------------------------------------------
// End-to-end: a Chaitanya-style resume surfaces certs + achievements
// --------------------------------------------------------------------

test('end-to-end: achievements section + inline certs line, both surface', () => {
  // Modelled on the Chaitanya resume — achievement section header
  // followed by a single-line content, then a "Certifications: …"
  // line listing two credentials. The previous build extracted 0 of
  // each; now we get 1 achievement statement + 2 certs.
  const sample = [
    'EXPERIENCE',
    'Software Engineer · Acme',
    'Built things and shipped them.',
    '',
    'AWARDS & ACHIEVEMENTS',
    'Heroes Award, Kudos Award & Developer of the Month - Acme Corp',
    'Certifications: Azure DevOps Engineer Expert (2025), Azure Developer Associate (2025)',
  ].join('\n');
  const mapped = mapParsedResume(parseResumeText(sample));
  assert.ok((mapped.achievements || []).length >= 1,
    `expected >=1 achievement, got ${(mapped.achievements || []).length}`);
  const certNames = (mapped.certifications || []).map((c) => c.name);
  assert.ok(certNames.some((n) => /Azure.*Engineer/i.test(n)),
    `expected Azure Engineer in ${JSON.stringify(certNames)}`);
  assert.ok(certNames.some((n) => /Azure.*Associate/i.test(n)),
    `expected Azure Associate in ${JSON.stringify(certNames)}`);
});
